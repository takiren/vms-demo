package clip

import (
	"errors"
	"fmt"
	"regexp"
	"strconv"
	"strings"
	"time"
)

// AudioMode says what happened to the audio of a clip (the X-VMS-Audio
// response header).
type AudioMode string

// Audio modes.
const (
	// AudioIncluded: the first audio stream is copied.
	AudioIncluded AudioMode = "included"
	// AudioDropped: the recordings have audio, but it is left out because
	// the mp4 muxer cannot hold it by stream copy (e.g. G.711) or it is not
	// the same in every segment.
	AudioDropped AudioMode = "dropped"
	// AudioNone: the recordings have no audio.
	AudioNone AudioMode = "none"
)

// ErrIncompatible means the segments cannot be joined by stream copy
// (the video format changes within the range, or is not one mp4 holds).
var ErrIncompatible = errors.New("clip: recordings cannot be joined without transcoding")

// mp4VideoCodecs are the video codecs a clip may carry (what cameras send
// and the design allows: H.264 / H.265).
var mp4VideoCodecs = map[string]bool{"h264": true, "hevc": true}

// mp4AudioCodecs are the audio codecs FFmpeg's mp4 muxer stores by stream
// copy. G.711 (pcm_alaw / pcm_mulaw), common on cameras, is not one of
// them, and there is no transcoding (no audio encoders in the LGPL build).
var mp4AudioCodecs = map[string]bool{
	"aac": true, "opus": true, "mp3": true, "ac3": true, "eac3": true, "flac": true, "alac": true,
}

// checkVideo requires every segment's first video stream to be a supported
// codec with the same parameters: stream copy keeps the first segment's
// codec configuration, so a camera reconfigured mid-range would produce a
// broken file. starts are the recordings' start times (for the message).
func checkVideo(probes []Streams, starts []time.Time) error {
	if len(probes) == 0 {
		return nil
	}
	for i, p := range probes {
		if len(p.Video) == 0 {
			return fmt.Errorf("%w: the recording at %s has no video", ErrIncompatible, starts[i].UTC().Format(time.RFC3339))
		}
	}
	first := probes[0].Video[0]
	if !mp4VideoCodecs[first.Codec] {
		return fmt.Errorf("%w: video codec %q is not supported (H.264 or H.265 only)", ErrIncompatible, first.Codec)
	}
	for i, p := range probes[1:] {
		if v := p.Video[0]; v != first {
			return fmt.Errorf("%w: the video format changes at %s (%s → %s); split the range there",
				ErrIncompatible, starts[i+1].UTC().Format(time.RFC3339), describeVideo(first), describeVideo(v))
		}
	}
	return nil
}

func describeVideo(v VideoStream) string {
	return fmt.Sprintf("%s %s %dx%d %s", v.Codec, v.Profile, v.Width, v.Height, v.PixFmt)
}

// decideAudio includes the first audio stream only if every segment has
// one, the codec is one mp4 holds, and its parameters never change.
// Otherwise the audio is dropped rather than failing the export.
func decideAudio(probes []Streams) AudioMode {
	withAudio := 0
	for _, p := range probes {
		if len(p.Audio) > 0 {
			withAudio++
		}
	}
	switch {
	case withAudio == 0:
		return AudioNone
	case withAudio < len(probes):
		return AudioDropped
	}
	first := probes[0].Audio[0]
	if !mp4AudioCodecs[first.Codec] {
		return AudioDropped
	}
	for _, p := range probes[1:] {
		if p.Audio[0] != first {
			return AudioDropped
		}
	}
	return AudioIncluded
}

// segmentName is the only form of file name a concat list may contain:
// generated by us, relative, and acceptable to the concat demuxer's
// -safe 1 (no protocol, no leading dot, only [A-Za-z0-9_.-]).
var segmentName = regexp.MustCompile(`^seg-[0-9]{5}\.mp4$`)

func segmentFile(i int) string { return fmt.Sprintf("seg-%05d.mp4", i) }

// listEntry is one file of an ffconcat list. Inpoint is in the file's own
// time in seconds; negative means none.
type listEntry struct {
	Name    string
	Inpoint float64
}

// concatList renders an ffconcat list. Names must match segmentName (they
// are never user input; this is a second line of defense against quoting
// and path problems).
func concatList(entries []listEntry) (string, error) {
	if len(entries) == 0 {
		return "", errors.New("clip: empty concat list")
	}
	var b strings.Builder
	b.WriteString("ffconcat version 1.0\n")
	for _, e := range entries {
		if !segmentName.MatchString(e.Name) {
			return "", fmt.Errorf("clip: refusing concat entry %q", e.Name)
		}
		b.WriteString("file '" + e.Name + "'\n")
		if e.Inpoint >= 0 {
			b.WriteString("inpoint " + strconv.FormatFloat(e.Inpoint, 'f', 6, 64) + "\n")
		}
	}
	return b.String(), nil
}

// segment is a recording that goes into a clip.
type segment struct {
	Start, End time.Time
	// StartTime is the file's first timestamp (ffprobe), in seconds.
	StartTime float64
}

// trimPlan cuts the clip to [from, to). Recordings are whole files, so
// only the first and the last can need cutting:
//
//   - start: the concat demuxer's inpoint on the first file. Stream copy
//     cannot start between keyframes, so the demuxer starts at the keyframe
//     at or before it: a clip may start up to one GOP early (FFmpeg marks
//     the extra frames with an edit list, which most players honor).
//   - end: the output's -t, the covered length of the segments (gaps
//     between recordings are not in the file). Not the concat outpoint:
//     it ends a file at the first packet past it, which drops the audio of
//     files whose tracks are poorly interleaved.
//
// inpoint < 0 and limit 0 mean no cut.
func trimPlan(segs []segment, from, to time.Time) (inpoint float64, limit time.Duration) {
	inpoint = -1
	if len(segs) == 0 {
		return inpoint, 0
	}
	if d := from.Sub(segs[0].Start); d > 0 {
		inpoint = segs[0].StartTime + d.Seconds()
	}
	if !to.Before(segs[len(segs)-1].End) {
		return inpoint, 0
	}
	for _, s := range segs {
		start, end := s.Start, s.End
		if start.Before(from) {
			start = from
		}
		if end.After(to) {
			end = to
		}
		if end.After(start) {
			limit += end.Sub(start)
		}
	}
	return inpoint, limit
}
